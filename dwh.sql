-- =======================================================
-- DDL (Data Definition Language)
-- =======================================================

CREATE SCHEMA IF NOT EXISTS dwh;

-- DIM Date
CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_key    INT         PRIMARY KEY,   
    full_date   DATE        NOT NULL UNIQUE,
    day         SMALLINT    NOT NULL,      
    month_num   SMALLINT    NOT NULL,      
    month_name  VARCHAR(10) NOT NULL,      
    quarter     SMALLINT    NOT NULL,      
    year        SMALLINT    NOT NULL,
    is_weekend  BOOLEAN     NOT NULL       
);

-- DIM customer
CREATE TABLE IF NOT EXISTS dwh.dim_customer (
    customer_key   INT          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id    INT          NOT NULL UNIQUE,
    customer_name  VARCHAR(100) NOT NULL,
    city           VARCHAR(50)  NOT NULL,
    region         VARCHAR(50)  NOT NULL
);

-- DIM Driver
CREATE TABLE IF NOT EXISTS dwh.dim_driver (
    driver_key       INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id        INT          NOT NULL UNIQUE,
    driver_name      VARCHAR(100) NOT NULL,
    assigned_region  VARCHAR(50)  NOT NULL
);

-- DIM location
CREATE TABLE IF NOT EXISTS dwh.dim_location (
    location_key  INT         GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    city          VARCHAR(50) NOT NULL UNIQUE,
    region        VARCHAR(50) NOT NULL
);

-- DIM fact_shiments
CREATE TABLE IF NOT EXISTS dwh.fact_shipments (
    shipment_id               INT           PRIMARY KEY,
    shipment_date_key         INT           NOT NULL REFERENCES dwh.dim_date (date_key),
    delivery_date_key         INT           REFERENCES dwh.dim_date (date_key),
    customer_key              INT           NOT NULL REFERENCES dwh.dim_customer (customer_key),
    driver_key                INT           NOT NULL REFERENCES dwh.dim_driver (driver_key),
    origin_location_key       INT           NOT NULL REFERENCES dwh.dim_location (location_key),
    destination_location_key  INT           NOT NULL REFERENCES dwh.dim_location (location_key),
    weight_kg                 NUMERIC(10,2) NOT NULL,
    fuel_cost                 NUMERIC(14,2) NOT NULL DEFAULT 0,
    labor_cost                NUMERIC(14,2) NOT NULL DEFAULT 0,
    toll_cost                 NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_cost                NUMERIC(14,2) NOT NULL DEFAULT 0,
    days_to_deliver           INT,                         -- NULL kalau belum/tidak terkirim
    is_sla_breached           BOOLEAN       NOT NULL,      -- TRUE bila days_to_deliver > 5
    status                    VARCHAR(20)   NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_fact_ship_date  ON dwh.fact_shipments (shipment_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_customer   ON dwh.fact_shipments (customer_key);
CREATE INDEX IF NOT EXISTS idx_fact_dest       ON dwh.fact_shipments (destination_location_key);

-- =======================================================
-- ETL (Extract, Transform, Load)
-- =======================================================

-- DIM date
INSERT INTO dwh.dim_date (date_key, full_date, day, month_num, month_name,
                          quarter, year, is_weekend)
SELECT TO_CHAR(d.dt, 'YYYYMMDD')::int,
       d.dt,
       EXTRACT(DAY     FROM d.dt)::smallint,
       EXTRACT(MONTH   FROM d.dt)::smallint,
       TO_CHAR(d.dt, 'FMMonth'),
       EXTRACT(QUARTER FROM d.dt)::smallint,
       EXTRACT(YEAR    FROM d.dt)::smallint,
       EXTRACT(ISODOW  FROM d.dt) IN (6, 7)
FROM (SELECT DATE '2024-01-01' + g.n AS dt
      FROM generate_series(0, 365) AS g(n)) d
ON CONFLICT (date_key) DO NOTHING;

-- DIM Customer 
INSERT INTO dwh.dim_customer (customer_id, customer_name, city, region)
SELECT customer_id, customer_name, city, region
FROM public.customers
ON CONFLICT (customer_id) DO UPDATE
SET customer_name = EXCLUDED.customer_name,
    city          = EXCLUDED.city,
    region        = EXCLUDED.region;

-- DIM Driver
INSERT INTO dwh.dim_driver (driver_key, driver_id, driver_name, assigned_region)
OVERRIDING SYSTEM VALUE
VALUES (-1, -1, 'Unassigned', 'Unknown')
ON CONFLICT DO NOTHING;
 
INSERT INTO dwh.dim_driver (driver_id, driver_name, assigned_region)
SELECT DISTINCT driver_id, driver_name, assigned_region
FROM public.drivers
ON CONFLICT (driver_id) DO UPDATE
SET driver_name     = EXCLUDED.driver_name,
    assigned_region = EXCLUDED.assigned_region;

-- DIM location
WITH all_cities AS (
    SELECT origin_city      AS city FROM public.shipments
    UNION
    SELECT destination_city AS city FROM public.shipments
),
city_region AS (
    SELECT DISTINCT city, region FROM public.customers
)
INSERT INTO dwh.dim_location (city, region)
SELECT a.city, COALESCE(cr.region, 'Unknown')
FROM all_cities a
LEFT JOIN city_region cr ON cr.city = a.city
ON CONFLICT (city) DO UPDATE
SET region = EXCLUDED.region;

-- fact_shipments
INSERT INTO dwh.fact_shipments (
    shipment_id, shipment_date_key, delivery_date_key, customer_key, driver_key,
    origin_location_key, destination_location_key, weight_kg,
    fuel_cost, labor_cost, toll_cost, total_cost,
    days_to_deliver, is_sla_breached, status
)
SELECT s.shipment_id,
       TO_CHAR(s.shipment_date, 'YYYYMMDD')::int,
       TO_CHAR(s.delivery_date, 'YYYYMMDD')::int,
       dc.customer_key,
       COALESCE(dd.driver_key, -1),
       lo.location_key,
       ld.location_key,
       s.weight_kg,
       COALESCE(sc.fuel_cost,  0),
       COALESCE(sc.labor_cost, 0),
       COALESCE(sc.toll_cost,  0),
       COALESCE(sc.total_cost, 0),
       (s.delivery_date - s.shipment_date),
       COALESCE((s.delivery_date - s.shipment_date) > 5, FALSE),
       s.status
FROM public.shipments s
JOIN      dwh.dim_customer dc ON dc.customer_id = s.customer_id
JOIN      dwh.dim_location lo ON lo.city        = s.origin_city
JOIN      dwh.dim_location ld ON ld.city        = s.destination_city
LEFT JOIN public.shipment_costs sc ON sc.shipment_id = s.shipment_id
LEFT JOIN public.drivers        dr ON dr.shipment_id = s.shipment_id
LEFT JOIN dwh.dim_driver        dd ON dd.driver_id   = dr.driver_id
ON CONFLICT (shipment_id) DO UPDATE
SET delivery_date_key = EXCLUDED.delivery_date_key,
    driver_key        = EXCLUDED.driver_key,
    fuel_cost         = EXCLUDED.fuel_cost,
    labor_cost        = EXCLUDED.labor_cost,
    toll_cost         = EXCLUDED.toll_cost,
    total_cost        = EXCLUDED.total_cost,
    days_to_deliver   = EXCLUDED.days_to_deliver,
    is_sla_breached   = EXCLUDED.is_sla_breached,
    status            = EXCLUDED.status;

-- =================================================
-- Validasi hasil load
-- =================================================
SELECT s.status, COUNT(*) AS sumber,
       (SELECT COUNT(*) FROM dwh.fact_shipments f WHERE f.status = s.status) AS dwh
FROM public.shipments s GROUP BY s.status;

WITH src AS (
  SELECT EXTRACT(MONTH FROM s.shipment_date)::int AS m, SUM(sc.total_cost) AS c
  FROM public.shipments s JOIN public.shipment_costs sc ON sc.shipment_id = s.shipment_id GROUP BY 1),
dw AS (
  SELECT d.month_num AS m, SUM(f.total_cost) AS c
  FROM dwh.fact_shipments f JOIN dwh.dim_date d ON d.date_key = f.shipment_date_key GROUP BY 1)
SELECT COALESCE(src.m, dw.m) AS bulan, src.c AS sumber, dw.c AS dwh, src.c - dw.c AS selisih
FROM src FULL JOIN dw ON dw.m = src.m ORDER BY 1;